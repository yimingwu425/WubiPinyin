constexpr int kSchemaVersion = 1;
constexpr int kMinWeight = 1;
constexpr int kMaxWeight = 100000;
constexpr std::size_t kMaxUserTextBytes = 8 * 1024;

std::int64_t NowUnixSeconds() {
  return std::chrono::duration_cast<std::chrono::seconds>(
             std::chrono::system_clock::now().time_since_epoch())
      .count();
}

void SetError(std::string* error, const std::string& value) {
  if (error) {
    *error = value;
  }
}

bool Execute(sqlite3* database, const char* sql, std::string* error) {
  char* message = nullptr;
  const int result = sqlite3_exec(database, sql, nullptr, nullptr, &message);
  if (result == SQLITE_OK) {
    return true;
  }
  SetError(error, message ? message : sqlite3_errmsg(database));
  sqlite3_free(message);
  return false;
}

bool IsAsciiLowercaseCode(std::string_view code,
                          bool allow_apostrophe,
                          std::size_t maximum_length) {
  if (code.empty() || code.size() > maximum_length) {
    return false;
  }
  for (const char ch : code) {
    if (ch >= 'a' && ch <= 'z') {
      continue;
    }
    if (allow_apostrophe && ch == '\'') {
      continue;
    }
    return false;
  }
  return true;
}

bool IsPinyinCode(std::string_view code) {
  if (!IsAsciiLowercaseCode(code, true, 64) || code.front() == '\'' ||
      code.back() == '\'') {
    return false;
  }
  bool previous_was_apostrophe = false;
  bool has_letter = false;
  for (const char ch : code) {
    if (ch == '\'') {
      if (previous_was_apostrophe) {
        return false;
      }
      previous_was_apostrophe = true;
      continue;
    }
    has_letter = true;
    previous_was_apostrophe = false;
  }
  return has_letter;
}

bool ContainsDictionaryUnsafeCharacter(std::string_view value) {
  return value.find_first_of("\r\n\t") != std::string_view::npos;
}

std::string PathUtf8(const std::filesystem::path& path) {
#ifdef _WIN32
  const std::wstring native = path.wstring();
  if (native.empty()) {
    return {};
  }
  const int size = WideCharToMultiByte(CP_UTF8, 0, native.data(),
                                       static_cast<int>(native.size()), nullptr,
                                       0, nullptr, nullptr);
  std::string value(size, '\0');
  WideCharToMultiByte(CP_UTF8, 0, native.data(), static_cast<int>(native.size()),
                      value.data(), size, nullptr, nullptr);
  return value;
#else
  const std::u8string native = path.u8string();
  return {reinterpret_cast<const char*>(native.data()), native.size()};
#endif
}

bool ReplaceFileAtomically(const std::filesystem::path& temporary,
                           const std::filesystem::path& destination,
                           std::string* error) {
#ifdef _WIN32
  if (MoveFileExW(temporary.c_str(), destination.c_str(),
                  MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH)) {
    return true;
  }
  SetError(error, "Could not replace " + PathUtf8(destination));
  return false;
#else
  std::error_code rename_error;
  std::filesystem::rename(temporary, destination, rename_error);
  if (!rename_error) {
    return true;
  }
  SetError(error, rename_error.message());
  return false;
#endif
}

bool WriteDictionary(const std::filesystem::path& destination,
                     const std::string& dictionary_name,
                     const std::vector<UserEntry>& entries,
                     std::string* error) {
  std::filesystem::path temporary = destination;
  temporary += ".tmp";
  std::ofstream file(temporary, std::ios::binary | std::ios::trunc);
  if (!file) {
    SetError(error, "Could not create " + PathUtf8(temporary));
    return false;
  }

  file << "# Rime dictionary\n"
          "# Generated by WubiPinyin. Do not edit this file directly.\n"
          "# encoding: utf-8\n"
          "---\n"
       << "name: " << dictionary_name << "\n"
       << "version: \"1.0\"\n"
          "sort: by_weight\n"
          "...\n";
  for (const UserEntry& entry : entries) {
    file << entry.text << '\t' << entry.code << '\t' << entry.weight << '\n';
  }
  file.flush();
  if (!file) {
    SetError(error, "Could not write " + PathUtf8(temporary));
    return false;
  }
  file.close();
  return ReplaceFileAtomically(temporary, destination, error);
}

bool WriteSchemaOverride(const std::filesystem::path& destination,
                         int candidate_page_size,
                         std::string* error) {
  std::filesystem::path temporary = destination;
  temporary += ".tmp";
  std::ofstream file(temporary, std::ios::binary | std::ios::trunc);
  if (!file) {
    SetError(error, "Could not create " + PathUtf8(temporary));
    return false;
  }

  file << "# Generated by WubiPinyin. Do not edit this file directly.\n"
          "patch:\n"
       << "  \"menu/page_size\": " << candidate_page_size << '\n';
  file.flush();
  if (!file) {
    SetError(error, "Could not write " + PathUtf8(temporary));
    return false;
  }
  file.close();
  return ReplaceFileAtomically(temporary, destination, error);
}

